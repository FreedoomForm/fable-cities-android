// Traffic golden probe — runs the REAL web traffic/TrafficSim.js in Node on a minimal fake
// net (a single closed-loop lane, no junctions) and emits worldgen/TrafficGoldens.kt.
// The Kotlin port (worldgen/Traffic.kt) must reproduce spawn + IDM integration bit-exactly.
import { writeFileSync } from 'node:fs';
import { TrafficSim } from '../src/modules/traffic/TrafficSim.js';
import { VEHICLE_IDS, VEHICLE_SPECS } from '../src/modules/traffic/VehicleModels.js';
